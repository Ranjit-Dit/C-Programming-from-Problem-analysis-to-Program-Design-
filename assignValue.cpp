#include <iostream>
#include <string>

using namespace std;

int main()
{
    int i, j;
    double sale;
    char first;
    string str;

    i = 4;
    cout << "i = " << i << endl;

    j = 4 * 5 - 11;
    cout << "j = " << j << endl;
    sale = 0.02 * 1000;
    cout << "sale = " << sale << endl;

    first = 'D';
    cout << "first = " << first << endl;

    str = "It is a sunny day.";
    cout << "str = " << str << endl;

    return 0;
}